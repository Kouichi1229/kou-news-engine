import type {
  ClaimedProcessingJob,
  ProcessingJob,
  ProcessingLifecycle,
} from '../processing.types.js';

/**
 * The Processing State store, as the approved design describes it.
 *
 * ## What this interface deliberately does not offer
 *
 * There is **no** `release()` and no refund (`CLM-7`). A claim consumes an
 * attempt and nothing returns it; `requeue` puts a job back in the queue while
 * keeping the attempt spent, which is the only "try again" shape the policy
 * allows.
 *
 * There is no `complete()` either. Publishing derived content needs the
 * publication transaction and the derived schema, both still `OPEN`
 * (`SPEC-GAP-05`, `SPEC-GAP-04`), so the success path is out of this batch.
 *
 * There is no cancellation or recovery entry point: *when* queued work is
 * cancelled and in what order recovery runs are `SPEC-GAP-08`, and the
 * terminal-reason precedence is L-01.
 */
export interface ProcessingJobRepository {
  /**
   * Opens a lifecycle. The identity is generated by the caller, never derived
   * from the URL (`A.1`, `OUT-17`).
   *
   * Throws when the article already has an open lifecycle: at most one may be
   * open per article (`A.1` partial unique index).
   */
  openLifecycle(input: {
    lifecycleId: string;
    articleId: string;
    openedAt: string;
  }): Promise<void>;

  /**
   * Creates a `pending` job for an explicitly supplied version.
   *
   * It does not decide *what constitutes* a new version — that rule is
   * `SPEC-GAP-05`. The caller supplies the number; this only records it.
   */
  createJob(input: {
    lifecycleId: string;
    processingVersion: number;
    createdAt: string;
  }): Promise<void>;

  /**
   * Atomically claims **one explicitly named job** and retires stale jobs.
   *
   * The target is supplied, never chosen. Selecting "the next job" would decide
   * scheduling — fairness, starvation, which lifecycle runs first — and that is
   * `SPEC-GAP-08`, still `OPEN`.
   *
   * Inside the same `BEGIN IMMEDIATE` transaction, before the claim:
   *
   * 1. every unfinished job whose version is below its lifecycle's
   *    `published_version` is terminalized as `superseded`, with its lease
   *    invalidated and no attempt consumed (`CLM-19`). Rows in abandoned or
   *    closed lifecycles are excluded from that pass because a second label
   *    (`cancelled`, `expired-unprocessed`) would also apply, and the
   *    precedence is L-01, still `OPEN`;
   * 2. the named job is claimed if it is `pending`, has attempts remaining, and
   *    its lifecycle is open, not abandoned, and not ahead of it (`CLM-18`,
   *    `CLM-19`).
   *
   * The claim increments `attempts` and installs the token and lease in the same
   * statement (`CLM-5`, `CLM-6`).
   *
   * Returns `undefined` when the named job is not claimable.
   */
  claim(input: {
    lifecycleId: string;
    processingVersion: number;
    owner: string;
    token: string;
    now: number;
    leaseDurationMs: number;
    updatedAt: string;
  }): Promise<ClaimedProcessingJob | undefined>;

  /**
   * Returns a running job to `pending` after a retryable failure, **keeping the
   * spent attempt** (`CLM-7`). Fenced on the token.
   *
   * Refuses at the ceiling: a job with three attempts is terminalized instead
   * (`CLM-8`, `CLM-10`).
   *
   * **`CLM-19` encounter point.** A Worker write is one of the places the
   * policy names, so the retirement pass runs first, in the same transaction.
   * A job whose version is below its lifecycle's `published_version` is
   * terminalized as `superseded` with its lease cleared, the fenced update then
   * matches nothing, and this method returns `false`. The caller must discard
   * its result; it must not treat `false` as "try again later".
   *
   * Rows in abandoned or closed lifecycles are excluded from that pass (the
   * label would compete with `cancelled` / `expired-unprocessed`, and that
   * precedence is L-01, still `OPEN`), so for those the pre-existing fencing
   * semantics apply unchanged.
   *
   * Returns `false` when the token no longer owns the row, for any reason.
   */
  requeue(input: {
    lifecycleId: string;
    processingVersion: number;
    token: string;
    failureCode: string;
    updatedAt: string;
  }): Promise<boolean>;

  /**
   * Terminalizes a running job with a caller-supplied marker.
   *
   * The marker's vocabulary is undecided (`CLM-9`, L-01); this method records
   * whatever the caller decides and never chooses a precedence itself. Fenced
   * on the token and on the `running` state, so a stale Worker cannot rewrite
   * an outcome that already committed (`CLM-12`, `CLM-19`).
   *
   * **`CLM-19` encounter point.** The retirement pass runs first, in the same
   * transaction, so a Worker reporting a failure or exhaustion for a job that a
   * newer publication has already retired cannot manufacture a
   * `failed_terminal` outcome or its alert: the job becomes `superseded`, the
   * fenced update matches nothing, and this method returns `false`.
   *
   * Committed outcomes are never matched by that pass, so history is not
   * rewritten from here. Abandoned and closed lifecycles are excluded, as in
   * `requeue` (L-01).
   */
  markTerminal(input: {
    lifecycleId: string;
    processingVersion: number;
    token: string;
    terminalReason: string;
    failureCode?: string | null;
    updatedAt: string;
  }): Promise<boolean>;

  /**
   * Reopens running jobs whose lease expired while attempts remain (`CLM-13`),
   * returning how many were reopened.
   *
   * Recovery invents no outcome: `attempts`, `failure_code` and
   * `terminal_reason` are left exactly as the last Worker left them, and no
   * alert is raised. A job carrying a committed terminal reason is not a
   * candidate, and neither is one at the attempt ceiling — exhaustion belongs to
   * `CLM-8`, which stays outside this operation until the alert sequencing
   * question (D-1) is settled.
   *
   * **`CLM-19` precedence.** The retirement pass runs first, in the same
   * transaction, so a job whose version is below its lifecycle's
   * `published_version` becomes `superseded` instead of being handed back to a
   * Worker. Abandoned and closed lifecycles are excluded from both steps
   * (L-01).
   *
   * `lease_expires_at = now` is not expired: the comparison is strict.
   */
  reopenExpired(input: { now: number; updatedAt: string }): Promise<number>;

  findJob(lifecycleId: string, processingVersion: number): Promise<ProcessingJob | undefined>;

  findLifecycle(lifecycleId: string): Promise<ProcessingLifecycle | undefined>;
}
